/** Obsidian 1.8.7+ exposes its configured UI language through the public API. */
export function translate(language: string, key: TranslationKey, params: Record<string, string> = {}): string {
	const normalized = language.toLowerCase().replace(/_/g, '-');
	const strings = ['zh', 'zh-cn', 'zh-sg', 'zh-hans'].includes(normalized) ? zh : en;
	return strings[key].replace(/\{(\w+)\}/g, (match, name: string) => params[name] ?? match);
}
export function t(key: TranslationKey, params: Record<string, string> = {}): string {
	return translate(getLanguage(), key, params);
}
